/// Names a caller would reasonably type that no prefix or substring of the
/// table's own names reaches. `Elves` is the table's one irregular plural -
/// every other method already answers to its natural singular.
const ALIASES: [(&str, &str); 1] = [("elf", "Elves")];

/// Match a query against the method names, ignoring case and surrounding
/// space. Exact wins over an alias, which wins over a prefix, which wins over
/// a substring - the multi-word methods are only reachable by substring,
/// because the `@` flag captures a single token.
pub fn find_method(query: &str) -> Option<&'static Method> {
    // "H.A.M. members" should answer to "ham", so punctuation is ignored on
    // both sides of the comparison.
    let plain = |s: &str| s.to_lowercase().replace(['.', '-', '\''], "");
    let needle = plain(query.trim());

    // Test the needle, not the query: a query of punctuation alone strips to
    // nothing, and an empty needle is a prefix of every name, so `@.` would
    // otherwise answer with whichever method happens to be listed first.
    if needle.is_empty() {
        return None;
    }

    let alias = ALIASES
        .iter()
        .find(|(alias, _)| *alias == needle)
        .map(|(_, name)| *name);

    METHODS
        .iter()
        .find(|method| plain(method.name) == needle)
        .or_else(|| alias.and_then(|name| METHODS.iter().find(|method| method.name == name)))
        .or_else(|| {
            METHODS
                .iter()
                .find(|method| plain(method.name).starts_with(&needle))
        })
        .or_else(|| {
            METHODS
                .iter()
                .find(|method| plain(method.name).contains(&needle))
        })
}

/// The Grand Exchange takes 2% of a sale, rounded down, capped per item.
const GE_TAX_PERCENT: f64 = 0.02;
const GE_TAX_CAP: f64 = 5_000_000.0;

/// Fish an item's buy price out of the item database and price list.
///
/// This is the `high` value with no fallback, which is what `-price` reports.
/// `common::price_of` deliberately differs - it falls back to `low` - so a
/// figure here can be checked with `-price` and agree.
fn ge_high(items: &[Mapping], ge: &HashMap<u32, Price>, name: &str) -> Option<u32> {
    let id = items
        .iter()
        .find(|item| item.name.eq_ignore_ascii_case(name))?
        .id;

    ge.get(&id)?.high
}

fn tax(price: f64) -> f64 {
    (price * GE_TAX_PERCENT).floor().min(GE_TAX_CAP)
}

/// Which side of the ledger a line sits on. The Grand Exchange takes its cut
/// when you sell, so an output nets less than its price while an input costs
/// exactly its price.
#[derive(Debug, Clone, Copy, PartialEq)]
enum Side {
    Input,
    Output,
}

/// What one of an item is worth, net of tax where tax applies. `None` when the
/// item cannot be priced at all.
fn value_of(loot: &Loot, side: Side, items: &[Mapping], ge: &HashMap<u32, Price>) -> Option<f64> {
    let net = |gross: f64| match side {
        Side::Output => gross - tax(gross),
        Side::Input => gross,
    };

    match loot.value {
        // Coins are not sold, so no lookup and no tax.
        Value::Coins => Some(1.0),
        // Raw and untaxed, deliberately: `{{EasyClueValue}}` expands to
        // `{{Average drop value|...|raw=yes}}`, which multiplies raw prices
        // and applies no tax. Taxing it here would be wrong as often as it
        // was right - a casket's contents include untradeables that the wiki
        // values by high alch, and an alch pays no Grand Exchange tax.
        Value::EasyCasketRolls(n) => Some(n * EASY_CASKET_ROLL_GP),
        Value::MasterCasketRolls(n) => Some(n * MASTER_CASKET_ROLL_GP),
        Value::CrystalShard => {
            let divine = ge_high(items, ge, "Divine super combat potion(4)")? as f64;
            let plain = ge_high(items, ge, "Super combat potion(4)")? as f64;

            Some(net((divine - plain) * 2.5))
        }
        Value::Ge => Some(net(ge_high(items, ge, loot.item)? as f64)),
    }
}

/// An hour of a method, in gp.
#[derive(Debug, PartialEq)]
pub struct Hourly {
    pub outputs: i64,
    pub inputs: i64,
    pub profit: i64,
    /// At least one line the Grand Exchange has to price resolved. Coins and
    /// caskets are excluded on purpose: they are constants, so they resolve
    /// against an empty price list and would make a fabricated total look
    /// like a real one.
    pub priced: bool,
    /// At least one item had no buy price, so the totals understate reality.
    pub unpriced: bool,
}

/// One side of the ledger, totalled, and how the market treated it.
struct Tally {
    gp: f64,
    priced: bool,
    unpriced: bool,
}

/// Total one side of the ledger. Per-pickpocket loot scales with the rate;
/// hourly loot is counted once.
fn total(
    loot: &[Loot],
    side: Side,
    rate: f64,
    items: &[Mapping],
    ge: &HashMap<u32, Price>,
) -> Tally {
    let mut tally = Tally {
        gp: 0.0,
        priced: false,
        unpriced: false,
    };

    for line in loot {
        match value_of(line, side, items, ge) {
            Some(value) => {
                let amount = if line.per_hour {
                    line.qty
                } else {
                    line.qty * rate
                };
                tally.gp += amount * value;
                tally.priced |= line.value.needs_market();
            }
            // Only a line the market prices can fail to resolve.
            None => tally.unpriced = true,
        }
    }

    tally
}

fn hourly(method: &Method, items: &[Mapping], ge: &HashMap<u32, Price>) -> Hourly {
    let outputs = total(method.outputs, Side::Output, method.rate, items, ge);
    let inputs = total(method.inputs, Side::Input, method.rate, items, ge);

    Hourly {
        outputs: outputs.gp.round() as i64,
        inputs: inputs.gp.round() as i64,
        profit: (outputs.gp - inputs.gp).round() as i64,
        priced: outputs.priced || inputs.priced,
        unpriced: outputs.unpriced || inputs.unpriced,
    }
}

/// Signed gp is coloured by sign rather than by the c1/c2 palette: those two
/// colours are per-user configurable and carry no profit/loss meaning.
const GREEN: &str = "\x0303";
const RED: &str = "\x0304";

fn gp(amount: i64) -> String {
    format!(
        "{}{}",
        if amount < 0 { RED } else { GREEN },
        short_gp(amount)
    )
}

/// `3,000 pickpockets/hr`. H.A.M.'s unit is easy clues, so the unit is carried
/// on the method rather than assumed.
fn rate_line(method: &Method) -> String {
    format!("{} {}/hr", commas(method.rate, "d"), method.rate_name)
}

fn xp_per_hour(method: &Method) -> f64 {
    method.rate * method.xp
}

/// The Thieving listing to work from: the player's, or one conjured from `^N`.
fn thieving(source: &Source, prefix: &str, flags: &StatsFlags) -> Result<Listing, Vec<String>> {
    if flags.start > 0 {
        let xp = if flags.start > MAX_SKILL_LEVEL {
            flags.start
        } else {
            level_to_xp(flags.start)
        };

        return Ok(Listing::Entry(Entry {
            name: HiscoreName::Thieving,
            level: xp_to_level(xp),
            xp,
            rank: 0,
        }));
    }

    let joined: String = strip_stats_parameters(&source.query)
        .split_whitespace()
        .collect::<Vec<&str>>()
        .join(" ");

    let hiscores = match collect_hiscores(&joined, source, flags) {
        Ok(hiscores) => hiscores,
        Err(_) => {
            return Err(vec![format!(
                "{} {}",
                prefix,
                source.c1("No hiscores found")
            )]);
        }
    };

    match hiscores.skill("Thieving") {
        Some(listing) => Ok(listing),
        None => Err(vec![format!(
            "{} {}",
            prefix,
            source.c1("No Thieving level found")
        )]),
    }
}

/// Every method ranked by profit, most profitable first. Methods above the
/// caller's level are kept - the market answer is useful before the level is -
/// but marked `*`. A method the market could not fully price is marked `?`,
/// because its number is the only one on the line that is not real and the
/// caller has no other way to tell which it is.
fn ranked(
    source: &Source,
    prefix: &str,
    level_string: &str,
    level: u32,
    items: &[Mapping],
    ge: &HashMap<u32, Price>,
) -> Vec<String> {
    let mut ranked: Vec<(&Method, Hourly)> = METHODS
        .iter()
        .map(|method| (method, hourly(method, items, ge)))
        .collect();

    // Every method still totals something against an empty price list - the
    // coin and casket constants do not need one - so a ranking built on it
    // would read as confident and be fiction. Bail rather than print it.
    if ranked.iter().all(|(_, hour)| !hour.priced) {
        return vec![format!("{} {}", prefix, source.c1("No prices"))];
    }

    ranked.sort_by(|(_, a), (_, b)| b.profit.cmp(&a.profit));

    let locked = ranked.iter().any(|(method, _)| level < method.thieving);
    let thin = ranked.iter().any(|(_, hour)| hour.unpriced);

    let parts: Vec<String> = ranked
        .iter()
        .map(|(method, hour)| {
            // A method can be both above your level and thinly priced, so the
            // marks stack rather than replace one another.
            let mut marks = String::new();
            if level < method.thieving {
                marks.push('*');
            }
            if hour.unpriced {
                marks.push('?');
            }

            format!(
                "{} {}{}",
                source.c1(method.name),
                gp(hour.profit),
                if marks.is_empty() {
                    String::new()
                } else {
                    source.c1(&marks)
                }
            )
        })
        .collect();

    let mut lines = pack_lines(
        &format!("{} {} {}", prefix, level_string, source.c1("Profit/hr:")),
        &parts,
        &source.c1(" | "),
        MAX_LINE_LEN,
    );

    let mut notes: Vec<String> = Vec::new();
    if locked {
        notes.push("* above your Thieving level".to_string());
    }
    if thin {
        notes.push("? some items have no buy price".to_string());
    }
    if !notes.is_empty() {
        lines.push(format!("{} {}", prefix, source.p(&notes.join(" | "))));
    }

    lines
}

/// One method, with what it takes to do it.
fn detail(
    source: &Source,
    prefix: &str,
    level_string: &str,
    level: u32,
    method: &Method,
    items: &[Mapping],
    ge: &HashMap<u32, Price>,
) -> Vec<String> {
    let hour = hourly(method, items, ge);

    let header = vec![
        source.c2(method.name),
        level_string.to_string(),
        source.c1(&rate_line(method)),
        vec![
            source.c2(&commas(method.xp, ".1f")),
            source.c1("XP each"),
            source.p(&format!(
                "{} XP/hr",
                short_gp(xp_per_hour(method).round() as i64)
            )),
        ]
        .join(" "),
    ]
    .join(&source.c1(" | "));

    let money = vec![
        vec![source.c1("Profit/hr"), gp(hour.profit)].join(" "),
        vec![
            source.c1("Outputs"),
            source.c2(&commas(hour.outputs as f64, "d")),
        ]
        .join(" "),
        vec![
            source.c1("Inputs"),
            source.c2(&commas(hour.inputs as f64, "d")),
        ]
        .join(" "),
    ]
    .join(&source.c1(" | "));

    let mut lines = vec![
        format!("{} {}", prefix, header),
        format!("{} {}", prefix, money),
        format!(
            "{} {} {}",
            prefix,
            source.c1("Requires"),
            method
                .requirements
                .iter()
                .map(|req| source.c2(req))
                .collect::<Vec<String>>()
                .join(&source.c1(" | "))
        ),
    ];

    if level < method.thieving {
        lines.push(format!(
            "{} {}",
            prefix,
            source.c1(&format!("Requires {} Thieving", method.thieving))
        ));
    }

    if hour.unpriced {
        lines.push(format!(
            "{} {}",
            prefix,
            source.p("some items have no buy price, so the totals understate it")
        ));
    }

    lines
}

pub fn lookup(source: Source) -> Result<Vec<String>> {
    let prefix = source.l("Pickpocket");
    let flags = stats_parameters(&source.query);

    let items = get_item_db()?;
    let ge = get_ge_data()?;

    let listing = match thieving(&source, &prefix, &flags) {
        Ok(listing) => listing,
        Err(lines) => return Ok(lines),
    };

    let level = listing.actual_level();
    let (reported, virtual_level) = level_display(listing.level(), level);
    let level_string = vec![
        source.c1("Thieving"),
        source.c2(&reported.to_string()),
        virtual_level.map_or(String::new(), |lvl| source.p(&lvl.to_string())),
    ]
    .join(" ")
    .trim_end()
    .to_string();

    if flags.search.is_empty() {
        return Ok(ranked(&source, &prefix, &level_string, level, &items, &ge));
    }

    let method = match find_method(&flags.search) {
        Some(method) => method,
        None => {
            return Ok(vec![format!(
                "{} {}",
                prefix,
                source.c1(&format!(
                    "'{}' isn't a pickpocketing method - try -pickpocket for the full list",
                    flags.search
                ))
            )]);
        }
    };

    Ok(detail(
        &source,
        &prefix,
        &level_string,
        level,
        method,
        &items,
        &ge,
    ))
}

