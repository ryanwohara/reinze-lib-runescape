/// Average value of ONE ROLL of a reward casket's standard drop table, in gp.
///
/// Per roll, not per casket. A casket rolls its table several times - an easy
/// casket 2-4 times, a master casket 5-7 - so a whole casket is worth the
/// average roll count times this, which is what the `Value` variants below
/// count. `{{EasyClueValue}}` is the value of one roll, not of one casket.
///
/// Not a Grand Exchange price: a casket's worth comes from its reward table -
/// 283 drop rows for easy, a 170-term expression for master - so the wiki
/// evaluates those and the results are baked in here. Generated by
/// `scripts/gen-clue-values.js`; re-run it to refresh.
pub const EASY_CASKET_ROLL_GP: f64 = 9_773.0;
pub const MASTER_CASKET_ROLL_GP: f64 = 108_946.0;

/// How one line of loot is priced.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Value {
    /// Looked up in the item database by name.
    Ge,
    /// Coins are worth one gp each, and selling them is not a thing.
    Coins,
    /// This many ROLLS of the easy casket's reward table - not this many
    /// caskets. An easy casket rolls 2-4 times, averaging 3, so one easy
    /// casket is `EasyCasketRolls(3.0)`.
    EasyCasketRolls(f64),
    /// This many ROLLS of the master casket's reward table - not this many
    /// caskets. A master casket rolls 5-7 times, averaging 6, so one master
    /// casket is `MasterCasketRolls(6.0)`.
    MasterCasketRolls(f64),
    /// Crystal shards do not trade. The wiki values one as the margin a
    /// divine super combat potion carries over a plain one, over 2.5 shards.
    CrystalShard,
}

impl Value {
    /// Whether pricing this line needs the Grand Exchange. Coins and caskets
    /// are constants, so they resolve even when the price list is empty -
    /// counting them as priced would hide an empty list.
    const fn needs_market(self) -> bool {
        matches!(self, Value::Ge | Value::CrystalShard)
    }
}

/// One line of a method's inputs or outputs.
pub struct Loot {
    pub item: &'static str,
    /// Expected amount per pickpocket, unless `per_hour` is set. Already
    /// includes drop rates and the rogue-equipment doubling.
    pub qty: f64,
    pub value: Value,
    /// Counted once an hour rather than once per pickpocket.
    pub per_hour: bool,
}

impl Loot {
    const fn ge(item: &'static str, qty: f64) -> Self {
        Self {
            item,
            qty,
            value: Value::Ge,
            per_hour: false,
        }
    }

    const fn ge_hourly(item: &'static str, qty: f64) -> Self {
        Self {
            item,
            qty,
            value: Value::Ge,
            per_hour: true,
        }
    }

    const fn coins(qty: f64) -> Self {
        Self {
            item: "Coins",
            qty,
            value: Value::Coins,
            per_hour: false,
        }
    }

    const fn coins_hourly(qty: f64) -> Self {
        Self {
            item: "Coins",
            qty,
            value: Value::Coins,
            per_hour: true,
        }
    }
}

