    /// The rendered lines as the caller reads them, with the colour codes
    /// taken out. Every code this module emits is `\x03` plus exactly two
    /// digits, so two digits is what gets dropped - any more would eat the
    /// leading digits of a gp figure.
    fn plain_lines(lines: &[String]) -> String {
        let mut out = String::new();

        for line in lines {
            let mut chars = line.chars().peekable();

            while let Some(c) = chars.next() {
                if c != '\x03' {
                    out.push(c);
                    continue;
                }

                for _ in 0..2 {
                    if matches!(chars.peek(), Some(c) if c.is_ascii_digit()) {
                        chars.next();
                    }
                }
            }

            out.push('\n');
        }

        out
    }

    /// One method's `name profit[marks]` entry, pulled out of the ranked
    /// lines by name.
    fn entry_for(lines: &[String], name: &str) -> String {
        let text = plain_lines(lines);
        let start = text
            .find(name)
            .unwrap_or_else(|| panic!("{} is missing from {:?}", name, text));

        text[start..]
            .split(" | ")
            .next()
            .and_then(|entry| entry.split('\n').next())
            .expect("an entry")
            .to_string()
    }

