#!/usr/bin/env python3
"""Generate the combat and Slayer src/params/<skill>.rs from src/npc/data.rs.

Offline generator, run by hand, output committed -- the same arrangement as
bin/gen-params.py producing the other seventeen skills from lib/Database.ini.

Reading the generated Rust rather than re-scraping the wiki is deliberate: it
keeps this offline and deterministic, and guarantees -params and -npc can never
disagree, because both answer from the same file. Entries keep data.rs order.

Run from anywhere; paths resolve against the repository root.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "params"
DATA = ROOT / "src" / "npc" / "data.rs"

# Section -> the NpcMetadata field it is served from. The four attack styles
# share combat_xp exactly, as they shared one set of values in the INI.
SECTIONS = {
    "Attack": "combat_xp",
    "Strength": "combat_xp",
    "Defence": "combat_xp",
    "Ranged": "combat_xp",
    "Hitpoints": "hitpoints_xp",
    "Slayer": "slayer_xp",
}

# Positional arguments of NpcMetadata::create, in order.
FIELDS = [
    "name", "members", "hitpoints", "attack", "defence", "magic", "ranged",
    "stab", "slash", "crush", "magic_def", "light_ranged", "std_ranged",
    "heavy_ranged", "flat_armor", "weakness", "combat_xp", "hitpoints_xp",
    "slayer_req", "slayer_xp", "slayer_categories", "slayer_masters",
]

# A string literal (rustfmt may put .to_string() on the following line), a
# float, an integer, or a bool. Order matters: the string alternative has to
# win before the digits inside one can be mistaken for a number of their own.
TOKEN = re.compile(
    r'"(?:[^"\\]|\\.)*"\s*\.to_string\(\)|-?\d+\.\d+|-?\d+|true|false'
)
ENTRY = re.compile(r"\n\s+Npc::(\w+) => Self::create\(")
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')


def parse(text: str) -> list[tuple[str, dict[str, str]]]:
    """[(variant, {field: literal})] for every NpcMetadata::create block."""
    body = text[text.index("pub fn from(npc: &Npc)"):]
    chunks = ENTRY.split(body)
    expected = len(chunks) // 2
    out = []
    for i in range(1, len(chunks), 2):
        variant, args = chunks[i], chunks[i + 1]
        tokens = TOKEN.findall(args)[: len(FIELDS)]
        if len(tokens) != len(FIELDS):
            print(
                f"{variant}: found {len(tokens)} of {len(FIELDS)} arguments",
                file=sys.stderr,
            )
            return []
        out.append((variant, dict(zip(FIELDS, tokens))))
    if len(out) != expected:
        print(f"parsed {len(out)} of {expected} entries", file=sys.stderr)
        return []
    return out


def name_of(literal: str) -> str:
    return STRING.match(literal.strip()).group(1)


def number(literal: str) -> str:
    """The f64 literal as the params tables write values.

    Faithful to the source -- only a trailing `.0` is dropped, so `380.0`
    becomes `380` while `126.67` is left alone. Deliberately not re-derived
    through a float, which is what would let repr noise back in.
    """
    literal = literal.strip()
    return literal[:-2] if literal.endswith(".0") else literal


def rust_string(value: str) -> str:
    """A Rust string literal body. Names carry apostrophes and hyphens."""
    return value.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    if not DATA.exists():
        print(f"cannot find data.rs at {DATA}", file=sys.stderr)
        return 1

    npcs = parse(DATA.read_text(encoding="utf-8"))
    if not npcs:
        return 1

    OUT.mkdir(parents=True, exist_ok=True)
    written = []
    for section, field in SECTIONS.items():
        entries = []
        for variant, npc in npcs:
            # An entry that answers 0xp is never a useful result. It is what
            # separates the 1,246 assignable monsters from every other NPC
            # carrying a slayer_xp field.
            if npc[field] in ("0", "0.0"):
                continue
            if npc["name"] == "":
                continue
            entries.append((name_of(npc["name"]).replace(" ", "_"),
                            number(npc[field])))

        seen: dict[str, int] = {}
        for key, _ in entries:
            seen[key] = seen.get(key, 0) + 1
        duplicates = sorted(k for k, n in seen.items() if n > 1)
        if duplicates:
            print(
                f"  [{section}] {len(duplicates)} duplicate key(s): "
                f"{', '.join(duplicates[:5])}",
                file=sys.stderr,
            )

        module = section.lower()
        lines = [
            "// @generated by bin/gen-npc-params.py from src/npc/data.rs -- do not edit.",
            f"// Section [{section}], {len(entries)} entries, "
            f"from NpcMetadata::{field}, in data.rs order.",
            "",
            "pub const ENTRIES: &[(&str, &str)] = &[",
        ]
        for key, value in entries:
            lines.append(f'    ("{rust_string(key)}", "{rust_string(value)}"),')
        lines.append("];")
        lines.append("")
        (OUT / f"{module}.rs").write_text("\n".join(lines), encoding="utf-8")
        written.append((section, module, len(entries)))

    for section, module, count in sorted(written):
        print(f"  {module + '.rs':16} [{section}] {count} entries")
    print(f"{len(written)} files from {len(npcs)} NPCs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
